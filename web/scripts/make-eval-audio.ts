// Speaks the S7-5 voice-note and Live-turn scripts with the Live model and stores them as 16 kHz
// WAV files beside their manifests (web/tests/ai-evals/README.md, "Audio and photos"). Owner-run,
// once, with your own `gcloud auth application-default login` on project dryscope; never in CI.
// From web/:
//
//   npm run eval:audio
//
// It skips files already there with a matching SHA-256, keeps a clip only when the words the model
// spoke match the script (word error rate at most 5%, one retry), records each kept file's SHA-256
// in the manifest, and stops before its estimated spend passes $1. It prints counts only. Commit
// the WAV files and the two manifests afterwards.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSpeaker, SPEECH_MODEL, type Speaker } from '../src/lib/ai/eval-speech';
import { costMicroUsd } from '../src/lib/ai/pricing';
import { DATA_DIR, loadDataset } from '../tests/ai-evals/datasets';
import { readIfPresent, resample24kTo16k, sha256, updateManifest, wavFile } from '../tests/ai-evals/files';
import { wordErrorRate } from '../tests/ai-evals/text';

export const PROJECT = 'dryscope';
export const MAX_MICRO_USD = 1_000_000;
const MAX_WER = 0.05;
// A few of the 30 prebuilt voices, so the suites do not hear one speaker only.
export const VOICES = ['Charon', 'Kore', 'Puck', 'Aoede', 'Fenrir', 'Leda'] as const;

export class AudioArgsError extends Error {}

export function checkAudioEnv(argv: string[], env: Record<string, string | undefined>): void {
  for (const name of ['CI', 'GITHUB_ACTIONS', 'K_SERVICE', 'CLOUD_RUN_JOB']) {
    if (env[name]) throw new AudioArgsError(`refusing to run: ${name} is set (audio is generated by the owner, once)`);
  }
  if (argv.length > 0) throw new AudioArgsError('this command takes no arguments');
}

type Item = { id: string; text: string; file: string; sha256: string | null };
export type AudioCounts = { kept: number; skipped: number; mismatched: number; failed: number; stopped: boolean; costMicroUsd: number };

export async function makeAudio(
  sets: { name: 'voiceNotes' | 'liveTurns'; items: Item[] }[],
  speaker: Speaker,
  io: { read(path: string): Uint8Array | null; write(path: string, bytes: Uint8Array): void; record(name: 'voiceNotes' | 'liveTurns', changes: Map<string, { file: string; sha256: string }>): void },
  now: () => Date = () => new Date(),
): Promise<AudioCounts> {
  const counts: AudioCounts = { kept: 0, skipped: 0, mismatched: 0, failed: 0, stopped: false, costMicroUsd: 0 };
  let turn = 0;
  for (const set of sets) {
    const changes = new Map<string, { file: string; sha256: string }>();
    for (const item of set.items) {
      const present = io.read(`${DATA_DIR}${item.file}`);
      if (present && item.sha256 && sha256(present) === item.sha256) {
        counts.skipped += 1;
        continue;
      }
      if (counts.costMicroUsd >= MAX_MICRO_USD) {
        counts.stopped = true;
        break;
      }
      const voice = VOICES[turn % VOICES.length]!;
      turn += 1;
      let kept = false;
      let missed: 'failed' | 'mismatched' = 'failed';
      for (let attempt = 0; attempt < 2 && !kept; attempt += 1) {
        const spoken = await speaker.speak(item.text, voice);
        if (!spoken) {
          missed = 'failed';
          continue;
        }
        counts.costMicroUsd += costMicroUsd(SPEECH_MODEL, spoken.usage, now());
        if (wordErrorRate([{ reference: item.text, hypothesis: spoken.transcript }]) > MAX_WER) {
          missed = 'mismatched';
          continue;
        }
        const wav = wavFile(resample24kTo16k(spoken.pcm24k));
        io.write(`${DATA_DIR}${item.file}`, wav);
        changes.set(item.id, { file: item.file, sha256: sha256(wav) });
        kept = true;
        counts.kept += 1;
      }
      if (!kept) counts[missed] += 1;
    }
    if (changes.size > 0) io.record(set.name, changes);
    if (counts.stopped) break;
  }
  return counts;
}

async function main() {
  checkAudioEnv(process.argv.slice(2), process.env);
  const sets = [
    { name: 'voiceNotes' as const, items: loadDataset('voiceNotes').map((n) => ({ id: n.id, text: n.script, file: n.file, sha256: n.sha256 })) },
    { name: 'liveTurns' as const, items: loadDataset('liveTurns').map((t) => ({ id: t.id, text: t.say, file: t.file, sha256: t.sha256 })) },
  ];
  const counts = await makeAudio(sets, createSpeaker(PROJECT), {
    read: readIfPresent,
    write: (path, bytes) => {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, bytes);
    },
    record: updateManifest,
  });
  console.log(JSON.stringify(counts));
  return counts.failed === 0 && counts.mismatched === 0 && !counts.stopped;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().then(
    (complete) => process.exit(complete ? 0 : 1),
    (error: unknown) => {
      console.error(error instanceof AudioArgsError ? error.message : 'audio generation failed');
      process.exit(2);
    },
  );
}
