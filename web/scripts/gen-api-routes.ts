// Writes src/lib/api-routes.generated.ts: the route patterns of every file under src/app/api named
// route.ts, so a new API route never needs an edit to a shared list. The output is not committed
// (it is in .gitignore); it is made again by the scripts that need it (typecheck, lint, the
// vitest configs, next.config.ts for dev, build and start).
//
//   tsx scripts/gen-api-routes.ts
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const API_DIR = path.join(ROOT, 'src/app/api');
export const OUTPUT = path.join(ROOT, 'src/lib/api-routes.generated.ts');

// The route patterns of the route files under `apiDir`, sorted; a `[name]` segment is a parameter.
export function apiRoutePatterns(apiDir: string = API_DIR): string[] {
  return readdirSync(apiDir, { recursive: true, encoding: 'utf8' })
    .filter((file) => path.basename(file) === 'route.ts')
    .map((file) => `/api/${path.dirname(file).split(path.sep).join('/')}`)
    .sort();
}

export function renderApiRoutes(patterns: readonly string[]): string {
  return [
    '// Generated by scripts/gen-api-routes.ts from the route files under src/app/api. Not committed: do not edit.',
    'export const GENERATED_API_ROUTES: readonly string[] = [',
    ...patterns.map((pattern) => `  ${JSON.stringify(pattern)},`),
    '];',
    '',
  ].join('\n');
}

// Writes the module when its text would change, so a watching dev server is not restarted for nothing.
export function writeApiRoutes(output: string = OUTPUT, apiDir: string = API_DIR): void {
  const text = renderApiRoutes(apiRoutePatterns(apiDir));
  let current: string | undefined;
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    current = undefined;
  }
  if (current === text) return;
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeApiRoutes();
