const { test, expect } = require('@playwright/test');
const { checkScope } = require('./actions');
test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, serviceWorkers: 'block' });
const room = (page, key) => page.locator('[data-room-index="0"][data-room-key="' + key + '"]');
const row = (page, label) => page.locator('#sizingResult .sizing-row').filter({ hasText: label });
const EV = process.env.NM_EVIDENCE;
test('wall-only room (wet floor 0): air movers not sized, no flag, dehumidifier still sized, no air-mover sentence in letter', async ({ page, browserName }) => {
  test.skip(browserName !== 'chromium');
  await page.goto('/');
  await expect(page.locator('#address')).toBeEnabled({ timeout: 15000 });
  await checkScope(page);
  await page.locator('#address').fill('Synthetic wall-only property');
  await page.locator('#yearBuilt').fill('1998');
  await room(page, 'finished_sf').fill('40');
  await page.locator('#airMovers').fill('5');
  await page.locator('#dehumidifiers').fill('2');
  await page.locator('#rooms .room-more summary').first().click();
  await room(page, 'floor_sf').fill('600');
  await room(page, 'ceiling_height_ft').fill('8');
  await room(page, 'water_class').selectOption('2');
  await room(page, 'wet_floor_sf').fill('0');
  await expect(page.locator('#saveStatus')).toHaveText('Saved');
  const drawer = page.locator('#rooms .room-sizing').first();
  await expect(drawer.locator('.summary-note')).toHaveText('· air movers not sized: no wet floor · 96 pints/day');
  await page.locator('details.more-equipment summary').click();
  await page.locator('#dehumidifierPpd').fill('70');
  await expect(page.locator('#saveStatus')).toHaveText('Saved');
  await expect(row(page, 'Air movers')).toContainText('not sized');
  await expect(row(page, 'Air movers').locator('.sizing-flag')).toHaveCount(0);
  await expect(row(page, 'Air movers')).toContainText('Cannot size air movers: no wet floor area in Room 1.');
  await expect(row(page, 'Dehumidification')).toContainText('Recommended 96 pints/day');
  await expect(row(page, 'Dehumidification').locator('.sizing-flag')).toHaveText('Within range');
  await expect(page.locator('#sizingNote')).toContainText('air movers not sized');
  await expect(page.locator('#sizingNote')).not.toContainText('Air movers above');
  await expect(page.locator('#airMovers')).toHaveValue('5');
  await page.locator('#rooms .room').first().screenshot({ path: EV + '/wallonly-room.png' });
  await page.locator('details.more-equipment').screenshot({ path: EV + '/wallonly-equipment.png' });
  await page.locator('#scopeConfirmed').check();
  await expect(page.locator('#saveStatus')).toHaveText('Saved');
  await page.locator('#finishAudit').click();
  await expect(page.locator('#documents')).toBeVisible();
  const letter = await page.evaluate(() => state.documents.iicrc_defense_letter);
  require('fs').writeFileSync(EV + '/defense-letter-wallonly.txt', letter);
  expect(letter).toContain('Room 1: 600 SF floor × 8 ft ceiling = 4,800 cu ft, water class 2. LGR dehumidification: 4,800 ÷ 50 = 96 pints/day (AHAM).');
  expect(letter).not.toContain('Air movers for');
  expect(letter).toContain('Recommended: 96 pints/day of LGR dehumidification');
  expect(letter).not.toMatch(/Recommended: \d+ to \d+ air movers/);
  expect(letter).toContain('Entered for this proposal: 5 air movers and 2 LGR dehumidifiers rated 70 pints/day each.');
});
