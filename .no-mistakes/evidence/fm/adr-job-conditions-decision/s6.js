const { chromium } = require('playwright-core');
const fs = require('fs');
const BASE = 'http://localhost:8766', EV = process.argv[2];
const res = [];
const check = (c, d) => { res.push({ ok: !!c, d }); if (!c) console.log('FAIL', d); };
(async () => {
  await fetch(BASE + '/__test/workspaces', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ enabled: true }) });
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.addInitScript(() => sessionStorage.setItem('synthetic-uid', 'test-owner-ws-other'));
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(BASE + '/');
  await page.locator('#workspaceDashboard').waitFor({ state: 'visible' });
  await page.locator('#dashboardProfile').click();
  await page.getByRole('button', { name: 'Save company details' }).waitFor();
  const form = await page.locator('#dashboardContent').innerText();
  check(!/water.heater/i.test(form), 'profile form has no water-heater field');
  check((await page.locator('[name=water_heater_notice]').count()) === 0, 'no water_heater_notice input');
  await page.locator('#dashboardContent').screenshot({ path: EV + '/s6-other-company-settings.png' });
  await page.getByRole('button', { name: 'Save company details' }).click();
  await page.locator('#message').filter({ hasText: 'Company details saved' }).waitFor();
  check(true, 'profile saved');
  // Inspect stored profile via the server's own fake store would be internal; use the client-visible snapshot instead.
  await page.locator('#dashboardJobs').click();
  await page.waitForTimeout(800);
  fs.writeFileSync(EV + '/s6-jobs.txt', await page.locator('#dashboardContent').innerText());
  const newBtn = page.getByRole('button', { name: /new (inspection|job)/i }).first();
  await newBtn.click();
  await page.locator('#address').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('#address').disabled);
  await page.locator('.task-nav [data-task="property"]').click();
  for (const l of ['Crawl space exists', 'Cabinet removal under granite', 'Garage water-heater loss', 'This scope has been performed'])
    check((await page.getByText(l).count()) === 0, 'workspace form lacks ' + l);
  await page.locator('#address').fill('200 Other Co Rd, Fresno, CA');
  await page.locator('#yearBuilt').fill('1950');
  await page.locator('[data-room-key="finished_sf"]').first().fill('25');
  await page.locator('#scopeConfirmed').check();
  await page.locator('#saveDraft').click();
  await page.locator('#saveStatus').filter({ hasText: 'Saved' }).waitFor();
  await page.locator('#finishAudit').click();
  await page.locator('#documents').waitFor({ state: 'visible' });
  await page.locator('#proposalBody').filter({ hasText: 'valid for 30 days' }).waitFor();
  const text = await page.evaluate(() => [...document.querySelectorAll('#documents article.doc')].map((a) => '=== ' + a.id + ' ===\n' + a.textContent).join('\n\n'));
  fs.writeFileSync(EV + '/s6-other-company-documents.txt', text);
  check(text.includes('Per IICRC and EPA protocols, Other Restoration technicians will don'), 'protection names Other Restoration');
  check(text.includes('will NOT be the responsibility of Other Restoration'), 'exclusions name Other Restoration');
  check(!text.includes('responsibility of Alert Disaster Restoration') && !text.includes('Alert Disaster Restoration technicians'), 'ADR name not in other company clauses');
  check(!text.includes('Other company trade coordination.'), 'stored water-heater notice not printed');
  check(!/water heater|Can Do Crew|granite|crawl space/i.test(text), 'no retired wording');
  check(text.includes("Testing is required under California State Law due to the home's construction year."), 'pre-1978 testing paragraph');
  await page.locator('#proposalBody').screenshot({ path: EV + '/s6-other-company-proposal.png' });
  check(errors.length === 0, 'no page errors ' + errors.join(';'));
  await browser.close();
  await fetch(BASE + '/__test/workspaces', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ enabled: false }) });
  fs.writeFileSync(EV + '/s6-results.json', JSON.stringify(res, null, 2));
  console.log('failed', res.filter((r) => !r.ok).length, 'of', res.length);
})().catch((e) => { console.error(e.message.slice(0, 1500)); process.exit(1); });
