// Drives the real frontend against the harness: first audit model attempt stalls, retry succeeds.
import { chromium } from '@playwright/test';
const EV = process.argv[2];
const B = 'http://localhost:8799';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.request.post(B + '/__test/workspaces', { data: { enabled: false } });
await page.goto(B + '/');
const task = (n) => page.locator('.task-nav [data-task="' + n + '"]').click();
await task('property');
await page.locator('#address').fill('Synthetic stalled-audit property');
await page.locator('#yearBuilt').fill('1960');
await page.locator('[data-room-index="0"][data-room-key="name"]').fill('Bathroom');
await page.locator('[data-room-index="0"][data-room-key="finished_sf"]').fill('10');
await page.locator('#scopeConfirmed').check();
await page.locator('#saveDraft').click();
await page.locator('#saveStatus', { hasText: 'Saved privately' }).waitFor();
await page.request.post(B + '/__live/plan', { data: { delays: [60, 3] } });
const t0 = Date.now();
await page.locator('#finishAudit').click();
await page.waitForTimeout(10000);
await page.screenshot({ path: EV + '/ui-1-generating-during-stalled-first-attempt.png' });
await page.locator('#documents').waitFor({ state: 'visible', timeout: 60000 });
const secs = ((Date.now() - t0) / 1000).toFixed(1);
await page.waitForTimeout(500);
await page.screenshot({ path: EV + '/ui-2-documents-after-retry.png' });
await page.screenshot({ path: EV + '/ui-3-documents-after-retry-full.png', fullPage: true });
const msg = await page.locator('#message').innerText().catch(() => '');
const calls = await (await page.request.get(B + '/__live/calls')).json();
console.log(JSON.stringify({ documents_visible_after_s: Number(secs), message: msg, provider_calls: calls }, null, 1));
await browser.close();
