const { chromium } = require(process.argv[2] + '/node_modules/playwright');
const EV = process.argv[3];
const base = 'https://localhost:8932';
const log = (...a) => console.log(...a);
(async () => {
  const browser = await chromium.launch({ args: ['--ignore-certificate-errors'] });
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 390, height: 844 }, hasTouch: true, serviceWorkers: 'block' });
  const page = await ctx.newPage();
  page.on('response', (r) => { if (r.url().includes('jsQR')) log('fetched decoder:', r.url().replace(base, ''), r.status()); });
  const chip = (n) => page.locator('#roomChips').getByRole('button', { name: n, exact: true });
  const box = page.locator('#roomChips .room-chip-input');
  const rename = async (n) => { await box.waitFor(); await box.fill(n); await box.press('Enter'); await page.waitForTimeout(200); };
  const wait = async (fn, label, ms = 8000) => { const t = Date.now(); while (Date.now() - t < ms) { const v = await fn(); if (v) return v; await page.waitForTimeout(100); } throw Error('timeout: ' + label); };
  await page.goto(base + '/');
  await wait(() => page.locator('#address').isEnabled(), 'enabled', 15000);
  await wait(async () => (await page.locator('#saveStatus').textContent()) === 'Saved', 'saved', 15000);
  await chip('Room 1').click(); await rename('Kitchen');
  await page.locator('#addRoomChip').click(); await rename('Hallway');
  log('rooms:', await page.locator('#roomChips').innerText());
  // Make tags through the UI (server renders the QR).
  await page.locator('#printTags').click();
  const sheet = page.locator('#tagSheetDialog');
  await sheet.locator('#equipmentTagKind').selectOption('air_mover');
  await sheet.locator('#equipmentTagAsset').fill('am-0007');
  await sheet.locator('#addEquipmentTag').click();
  await sheet.locator('#makeTags').click();
  await wait(async () => (await sheet.locator('#tagPreview .tag-card').count()) >= 3, 'cards');
  const cards = await sheet.locator('#tagPreview .tag-card').evaluateAll((els) => els.map((e) => ({ title: e.querySelector('strong').textContent, code: e.querySelector('code').textContent, src: e.querySelector('img').src })));
  log('printed cards:', cards.map((c) => c.title + ' => ' + c.code));
  log('sheet status:', await sheet.locator('#tagSheetStatus').textContent());
  await page.screenshot({ path: EV + '/01-tag-sheet.png', fullPage: false });
  await page.evaluate(() => { document.body.classList.add('printing-tags'); document.getElementById('tagSheet').hidden = false; });
  await page.emulateMedia({ media: 'print' });
  await page.screenshot({ path: EV + '/01b-printed-tag-sheet.png', fullPage: true });
  await page.emulateMedia({ media: 'screen' });
  await page.evaluate(() => { document.body.classList.remove('printing-tags'); document.getElementById('tagSheet').hidden = true; });
  await sheet.locator('#closeTagSheet').click();
  const kitchenTag = cards.find((c) => c.title === 'Kitchen');
  const amTag = cards.find((c) => c.code.startsWith('DS1-EQ-AM'));
  // Synthetic camera that films a printed tag image; decoding uses the real vendored jsQR.
  await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 480; canvas.height = 480;
    const c = canvas.getContext('2d');
    setInterval(() => { c.fillStyle = '#fff'; c.fillRect(0, 0, 480, 480); if (window.__img && window.__img.complete) c.drawImage(window.__img, 60, 60, 360, 360); }, 100);
    window.__show = (src) => { const i = new Image(); i.src = src; window.__img = i; };
    Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: async () => canvas.captureStream(10) } });
  });
  log('jsQR is vendored function:', await page.evaluate(() => typeof window.jsQR));
  await chip('Hallway').click();
  await page.locator('#scanTag').click();
  const dlg = page.locator('#tagScanDialog');
  await wait(async () => /scanning/.test(await dlg.getAttribute('class')), 'scanning');
  await page.evaluate((s) => window.__show(s), amTag.src);
  const st = page.locator('#tagScanStatus');
  log('status after filming AM tag:', await wait(async () => { const t = await st.textContent(); return /placed/.test(t) && t; }, 'am placed'));
  await page.screenshot({ path: EV + '/02-camera-scan-equipment.png' });
  await page.evaluate((s) => window.__show(s), kitchenTag.src);
  log('status after filming Kitchen tag:', await wait(async () => { const t = await st.textContent(); return /Current room/.test(t) && t; }, 'room'));
  log('Kitchen chip pressed:', await chip('Kitchen').getAttribute('aria-pressed'));
  await page.screenshot({ path: EV + '/03-camera-scan-room.png' });
  await dlg.locator('#closeTagScan').click();
  log('video srcObject after close:', await page.evaluate(() => document.getElementById('tagVideo').srcObject));
  log('tagCount:', await page.locator('#tagCount').textContent());
  log('placements:', await page.locator('#equipmentPlacements').innerText());
  await page.locator('#equipmentPlacements').scrollIntoViewIfNeeded();
  await page.screenshot({ path: EV + '/04-placements.png' });
  // Adversarial: two rooms whose normalised names match.
  await chip('Hallway').click(); await page.waitForTimeout(200);
  if (await box.count() === 0) await chip('Hallway').click();
  await rename('  KITCHEN ');
  log('rooms after clash rename:', await page.locator('#roomChips').innerText());
  await page.locator('#scanTag').click();
  await dlg.locator('#tagCodeInput').fill('DS1-EQ-DH-DH-9');
  await dlg.locator('#applyTagCode').click();
  log('scan with clash:', await st.textContent());
  await page.screenshot({ path: EV + '/05-duplicate-room-scan-refused.png' });
  await dlg.locator('#closeTagScan').click();
  log('jsQR after scanning:', await page.evaluate(() => typeof window.jsQR));
  log('placements after rename:', (await page.locator('#equipmentPlacements').innerText()).replace(/\n/g,' | '));
  log('scans after refused scan:', JSON.stringify(await page.evaluate(() => (state.record.data.equipment_scans || []).map((s) => [s.asset_id, s.room]))));
  await page.locator('#printTags').click();
  await sheet.locator('#makeTags').click();
  await page.waitForTimeout(800);
  log('make tags with clash:', await sheet.locator('#tagSheetStatus').textContent(), '| cards:', await sheet.locator('#tagPreview .tag-card').count());
  await page.screenshot({ path: EV + '/06-duplicate-room-print-refused.png' });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
